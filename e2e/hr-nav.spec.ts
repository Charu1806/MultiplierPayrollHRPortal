import { test, expect } from '@playwright/test'

test.describe('HR tool and payroll navigation', () => {
  test('notifications sit last under People and payroll employees sit below review', async ({ page }) => {
    await page.goto('/people')

    const people = page.getByTestId('nav-people')
    await expect(people.getByRole('link', { name: 'Employees' })).toBeVisible({ timeout: 20000 })
    await expect(people).toContainText('HRIS tools and third party channels')
    const labels = (await people.locator('a, button').allTextContents()).map((text) => text.trim())
    expect(labels[0]).toBe('Employees')
    expect(labels.slice(1, 4)).toEqual(['Time off', 'Insurance', 'Expenses'])
    expect(labels.at(-1)).toMatch(/^Notifications/)
    await expect(people.getByRole('button', { name: 'Time off' })).toBeDisabled()
    await expect(people.getByRole('button', { name: 'Insurance' })).toBeDisabled()
    await expect(people.getByRole('button', { name: 'Expenses' })).toBeDisabled()

    const payroll = page.getByTestId('nav-payroll').getByRole('link')
    const payrollLabels = (await payroll.allTextContents()).map((text) => text.trim())
    const reviewAt = payrollLabels.findIndex((label) => label.startsWith('Review'))
    const employeesAt = payrollLabels.findIndex((label) => label === 'Employees')
    expect(reviewAt).toBeGreaterThanOrEqual(0)
    expect(employeesAt).toBeGreaterThan(reviewAt)
    expect(payrollLabels.at(-1)).toBe('Employees')
  })

  test('HR employees page has no payroll columns or Multiplier header', async ({ page }) => {
    await page.goto('/people')
    await expect(page.getByRole('columnheader', { name: 'Employee', exact: true })).toBeVisible({ timeout: 20000 })
    await expect(page.locator('header').getByText('Powered by Multiplier')).toHaveCount(0)
    await expect(page.getByRole('columnheader', { name: 'Pay status' })).toHaveCount(0)
    await expect(page.getByRole('columnheader', { name: 'Action needed' })).toHaveCount(0)
    await expect(page.getByRole('columnheader', { name: 'Pay this cycle' })).toHaveCount(0)
    await expect(page.getByRole('columnheader', { name: 'Base pay' })).toBeVisible()
    await expect(page.getByRole('columnheader', { name: 'Tax ID' })).toBeVisible()
    await expect(page.getByRole('columnheader', { name: 'Aadhaar' })).toBeVisible()
    await expect(page.getByRole('columnheader', { name: 'Bank' })).toBeVisible()
    await expect(page.getByRole('columnheader', { name: 'Insurance' })).toBeVisible()
    await expect(page.getByRole('columnheader', { name: 'Employee adds' })).toBeVisible()
  })

  test('notifications open inside the HR header', async ({ page }) => {
    await page.goto('/people/notifications')
    await expect(page).toHaveURL(/\/people\/notifications/)
    await expect(page.locator('header').getByText('People')).toBeVisible({ timeout: 20000 })
    await expect(page.locator('header').getByText('Powered by Multiplier')).toHaveCount(0)
    await expect(page.getByRole('navigation', { name: 'Breadcrumb' })).toContainText('Notifications')
    await expect(page.getByRole('button', { name: '← Back' })).toBeVisible()
    const alerts = page.getByRole('button', { name: /In-app alerts/ })
    await expect(alerts).toBeVisible()
    await expect(alerts).toContainText('V3')
    await expect(page.getByRole('button', { name: /Slack/ })).toContainText('V2')
  })

  test('overview stage dates come from the cycle', async ({ page }) => {
    await page.goto('/payroll/overview')
    await expect(page.getByText('Input close', { exact: true })).toBeVisible({ timeout: 20000 })
    await expect(page.getByText('Review window', { exact: true })).toBeVisible()
    await expect(page.getByText('Oct 16–19').first()).toBeVisible()
    await expect(page.getByText('Final report', { exact: true })).toBeVisible()
    await expect(page.getByText('Review closed', { exact: true })).toBeVisible()
    await expect(page.getByText('Oct 24–27').first()).toBeVisible()
    await expect(page.getByText(/Add funds · /)).toBeVisible()
    const summary = page.getByTestId('sync-summary')
    await expect(summary).toContainText('Add employees, bonuses, hikes, and missing details by Oct 15')
    await expect(summary).toContainText('Complete review by Oct 19')
    await expect(summary).toContainText('Final closure Oct 22')
    await expect(summary).toContainText('Payroll submitted')
    await expect(summary).toContainText('Pay day')
    await expect(summary).not.toContainText('Last sync')
    await expect(summary).not.toContainText(/\d+ bonus/)
    await expect(summary).not.toContainText(/\d+ hike/)
    await expect(summary).not.toContainText(/\d+ leave/)
    await expect(summary).not.toContainText(/\d+ other/)
    await expect(summary).not.toContainText('Manual')
    await expect(summary).not.toContainText('Workday')
    await expect(summary.getByText(/actions? need you/)).toHaveCount(1)
    await expect(page.getByText('Any October changes?')).toHaveCount(0)
    await expect(page.getByText(/before input finalisation/)).toHaveCount(0)
  })

  test('pay date outcome is not repeated on overview', async ({ page }) => {
    await page.addInitScript(() => localStorage.setItem('clarity.asOf', '2026-10-29'))
    await page.goto('/payroll/overview')
    await expect(page.getByText('Paid', { exact: true })).toBeVisible({ timeout: 20000 })
    const summary = await page.getByTestId('sync-summary').innerText()
    const paid = summary.match(/Simulated pay: (\d+) of (\d+) paid/)
    if (!paid) throw new Error(`simulated pay line missing: ${summary}`)
    await expect(page.getByText(`Paid Oct 29 · ${paid[1]} of ${paid[2]} employees received pay`)).toBeVisible()
    await expect(page.getByText('Pay date outcome')).toHaveCount(0)
    await expect(page.getByText('Still at risk')).toHaveCount(0)
    await expect(page.getByText('Moved to next cycle')).toHaveCount(0)
    await expect(page.getByText('Funds received from finance')).toHaveCount(0)
    await expect(page.getByText(/Payroll submitted for/)).toHaveCount(0)
  })
})
